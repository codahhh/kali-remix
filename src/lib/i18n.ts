export const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, fr };

export const languageNames: Record<Lang, string> = { en: 'English', fr: 'Français' };

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function localeFor(lang: Lang): string {
  return lang === 'fr' ? 'fr-FR' : 'en-GB';
}

export type Translator = (key: TranslationKey, vars?: Record<string, string | number>) => string;
